"""CLI: python -m tacticlens.personalize [localize|speech|report] [--live]

localize --live - Localizer agent + Translator back-translation for every golden explanation -> localized.json
speech --live   - Speech TTS for the audio persona (top moments, en/hi/es) -> audio/*.mp3 + audio.json
report          - localization stats + a 4 persona x 3 language sample -> docs/personalization.md
Live commands need AZURE_AI_PROJECT_ENDPOINT, AZURE_AI_MODEL_DEPLOYMENT, AZURE_AI_SERVICES_ENDPOINT, az login.
Golden mode never calls Azure: it reads the committed localized.json / audio.json.
"""
import asyncio
import json
import sys

from ..agents.eval import _dump, load, match_ids
from ..contracts import Persona
from ..sim.golden import GOLDEN_DIR
from .persona import index_explanations, personalize

ROOT = GOLDEN_DIR.parents[1]
AUDIO_TOP_N = 5
SAMPLE = ("GM01", "goal")


def _read(mid: str, name: str, default=None):
    path = GOLDEN_DIR / mid / name
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else default


async def localize_all() -> None:
    from .azure_rest import AzureRest
    from .localize import FoundryLocalizer, localize_match

    localizer, rest = FoundryLocalizer(), AzureRest()
    for mid in match_ids():
        meta, _ = load(mid)
        exps, trace = await localize_match(meta, _read(mid, "explanations.json"), localizer=localizer, rest=rest)
        _dump(GOLDEN_DIR / mid / "localized.json", {"backend": localizer.name, "explanations": exps, "trace": trace})
        print(mid, len(exps), "localized explanations")


async def speech_all() -> None:
    from .azure_rest import AzureRest
    from .speech import synthesize

    rest = AzureRest()
    for mid in match_ids():
        _, moments = load(mid)
        top = [m["id"] for m in sorted(moments, key=lambda m: -m["importance"])[:AUDIO_TOP_N]]
        exps = _read(mid, "explanations.json") + _read(mid, "localized.json", {}).get("explanations", [])
        index = await synthesize(GOLDEN_DIR / mid, exps, top, rest)
        _dump(GOLDEN_DIR / mid / "audio.json", index)
        print(mid, sum(len(v) for v in index.values()), "audio files")


def report() -> None:
    rows, totals = [], {}
    for mid in match_ids():
        loc = _read(mid, "localized.json", {})
        for langs in loc.get("trace", {}).values():
            for lang, entries in langs.items():
                done = next(e for e in entries if e["action"] == "done")
                t = totals.setdefault(lang, {"agent_ok": 0, "translator_ok": 0, "english_fallback": 0, "drift": 0})
                for k in ("agent_ok", "translator_ok", "english_fallback"):
                    t[k] += done[k]
                t["drift"] += sum(len(e.get("drift", [])) for e in entries if e["agent"] == "back_translator")
        audio = _read(mid, "audio.json", {})
        rows.append((mid, len(loc.get("explanations", [])), sum(len(v) for v in audio.values())))

    mid, kind = SAMPLE
    meta, moments = load(mid)
    moment = next(m for m in moments if m["kind"] == kind)
    exps = index_explanations(_read(mid, "explanations.json"), _read(mid, "localized.json", {}).get("explanations", []))
    audio = _read(mid, "audio.json", {})
    lines = ["# Personalization report", "",
             "Generated by `python -m tacticlens.personalize report` from the committed golden files.", "",
             "## Localization (Localizer agent -> numeral/entity checks -> Translator fallback -> back-translation)",
             "", "| lang | sentences by agent | by Translator fallback | English fallback | back-translation drift notes |",
             "|---|---|---|---|---|"]
    lines += [f"| {lang} | {t['agent_ok']} | {t['translator_ok']} | {t['english_fallback']} | {t['drift']} |"
              for lang, t in sorted(totals.items())]
    lines += ["", "| match | localized explanations | audio files |", "|---|---|---|"]
    lines += [f"| {r[0]} | {r[1]} | {r[2]} |" for r in rows]
    lines += ["", f"## One moment, 4 personas x 3 languages ({moment['id']}, {kind})", ""]
    for mode in ("analyst", "casual", "beginner", "audio"):
        for lang in ("en", "hi", "es"):
            persona = Persona(mode=mode, lang=lang, analogy="cricket" if mode == "casual" else "none")
            card = next(c for c in personalize([moment], meta, persona, exps, audio))
            flags = ", ".join(f for f in ("degraded", "analogy") if card[f]) or "verified"
            lines.append(f"**{mode} / {card['lang']}** ({flags}){' - audio: ' + card['audio'] if card['audio'] else ''}")
            lines.append("")
            for s in card["sentences"]:
                en = f" _(en: {s['en_text']})_" if s.get("en_text") else ""
                lines.append(f"- {s['text']}{en} `{', '.join(s['evidence_ids'])}`")
            lines.append("")
    (ROOT / "docs" / "personalization.md").write_text("\n".join(lines), encoding="utf-8")
    print("totals", totals, "| matches", rows)


def main(argv: list[str]) -> None:
    cmd = next((a for a in argv if not a.startswith("--")), "report")
    if cmd in ("localize", "speech") and "--live" not in argv:
        sys.exit(f"'{cmd}' calls Azure; pass --live (golden files are already committed)")
    if cmd == "localize":
        asyncio.run(localize_all())
    elif cmd == "speech":
        asyncio.run(speech_all())
    report()


if __name__ == "__main__":
    main(sys.argv[1:])
